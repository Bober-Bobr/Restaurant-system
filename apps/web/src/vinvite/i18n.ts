export type ViKey = keyof typeof dict.en;

export function viT(key: ViKey, locale: Locale): string {
  return dict[locale]?.[key] ?? dict.en[key];
}

// Hook: chrome translator bound to the store locale.
export function useViT(): (key: ViKey) => string {
  const locale = useVInviteStore((s) => s.locale);
  return (key) => viT(key, locale);
}
